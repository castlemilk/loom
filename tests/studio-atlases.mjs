import { chooseGraph } from './graph-picker.mjs'
import assert from 'node:assert/strict'
import { mkdir, readFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

export async function studioAtlases(context, home, touch = false) {
  const page = await context.newPage()
  page.setDefaultTimeout(15000)
  const errors = [], requests = []
  page.on('pageerror', (e) => errors.push(e.message))
  page.on('console', (msg) => { if (msg.type() === 'error') errors.push(msg.text()) })
  page.on('request', (r) => requests.push(r.url()))
  const click = (element) => touch ? element.tap() : element.click()
  const tab = (name) => page.getByRole('tab', { name, exact: true })
  const trail = page.getByRole('navigation', { name: 'Graph drilldown' })
  const selection = page.locator('#selection')
  const current = (title) => selection.getByText(title, {exact: true}).waitFor()
  const shots = new URL('../artifacts/studio/', import.meta.url)
  await mkdir(shots, { recursive: true })
  const shot = (name) => page.screenshot({ path: fileURLToPath(new URL('wikipedia-' + name + (touch ? '-mobile' : '-desktop') + '.png', shots)) })
  try {
    await page.goto(home)
    await click(page.getByRole('link', { name: 'Bauhaus', exact: true }))
    await page.locator('#totals').getByText('15 nodes · 52 links', { exact: true }).waitFor()
    assert.match(await page.title(), /Graph studio/i)
    await page.locator('#graph[data-ready]').waitFor()
    await page.locator('.graph-boundaries [data-bubble="Designers"]').waitFor({state:'attached'})
    await shot('bauhaus')
    const topics = page.locator('.atlas-directory')
    const label = page.getByRole('button', { name:'Browse Designers group' })
    let pannedX
    if (touch) await click(topics.getByRole('button', { name: /Designers/ }))
    else {
      const startX = await label.evaluate(el => parseFloat(el.style.left))
      await page.locator('#graph').press('ArrowRight')
      await page.waitForFunction(x => Math.abs(parseFloat(document.querySelector('[data-bubble-label="Designers"]').style.left) - x) < 1, startX - 32)
      pannedX = await label.evaluate(el => parseFloat(el.style.left))
      await click(label)
    }
    const roster = page.getByRole('list', { name: 'Designers members' })
    assert.equal(await roster.getByRole('button').count(), 6)
    await click(roster.locator('[data-member="Anni_Albers"]'))
    await current('Anni Albers')
    const source = page.getByRole('link', { name: 'Read on Wikipedia' })
    assert.match(await source.getAttribute('href'), /^https:\/\/en\.wikipedia\.org\/w\/index\.php\?oldid=\d+$/)
    const permalink = await page.getByRole('link', { name: 'Article permalink' }).getAttribute('href')
    const outgoing = page.getByRole('list', { name: 'Outgoing neighbors' })
    await click(outgoing.locator('[data-follow="Bauhaus"]'))
    await current('Bauhaus')
    assert.deepEqual(await trail.locator('li').allTextContents(), ['Overview','Designers','Bauhaus'])
    await click(page.getByRole('group', {name:'Link direction'}).getByRole('button', { name: /Incoming/ }))
    const incoming = page.getByRole('list', { name: 'Incoming neighbors' })
    await incoming.locator('[data-follow="Black_Mountain_College"]').waitFor()
    await click(trail.getByRole('button', { name:'Back one level' }))
    await current('Anni Albers')
    assert.equal(await roster.locator('[data-member="Anni_Albers"]').getAttribute('aria-pressed'), 'true')
    await click(page.locator('summary').filter({hasText:'Beyond this group'}))
    await click(page.getByRole('list', {name:'Neighbors outside this group'}).locator('[data-follow="Bauhaus"]'))
    await current('Bauhaus')
    await click(trail.getByRole('button', {name:'Overview', exact:true}))
    if (!touch) {
      // The label element mounts before the renderer projects its first restored frame.
      await page.waitForFunction(x => {
        const label = document.querySelector('[data-bubble-label="Designers"]')
        return label && Math.abs(parseFloat(label.style.left) - x) < 2
      }, pannedX)
      await click(page.getByRole('button', {name:'Fit view', exact:true}))
    }
    await click(tab('Style'))
    const graph = await page.locator('#graph').elementHandle()
    const style = page.getByRole('tabpanel', {name:'Style'})
    const option = (label) => style.locator('label').filter({has:page.getByRole('radio', {name:label, exact:true})})
    await click(option('Cross-hatch'))
    await click(option('Sketchy'))
    await click(option('Mist'))
    await page.locator('#hatch-spacing').press('ArrowRight')
    assert.equal(await style.getByRole('radio', {name:'Cross-hatch', exact:true}).isChecked(), true)
    assert.equal(await page.locator('#hatch-spacing-value').textContent(), '6 px')
    assert.equal(await page.locator('#studio-stage').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(233, 240, 237)')
    assert.ok(await graph.evaluate(el => el === document.querySelector('#graph')))
    await shot('drawing')
    if (touch) await click(page.getByRole('button', {name:'Find an article'}))
    else { await page.locator('#graph').focus(); await page.keyboard.press('/') }
    const search = page.locator('#find-node')
    await page.waitForFunction(() => document.activeElement?.id === 'find-node')
    await search.fill('laszlo')
    await search.press('Enter')
    await current('László Moholy-Nagy')
    await search.fill('textile')
    await click(page.locator('[data-result="Anni_Albers"]'))
    await current('Anni Albers')
    await chooseGraph(page, 'outer-solar-system')
    await page.locator('#totals').getByText('16 nodes · 62 links', {exact:true}).waitFor()
    assert.equal(new URL(page.url()).searchParams.get('example'), 'outer-solar-system')
    await page.reload()
    await page.locator('#totals').getByText('16 nodes · 62 links', {exact:true}).waitFor()
    assert.equal(await selection.count(), 0)
    await search.fill('voyager')
    await search.press('Enter')
    await current('Voyager 2')
    await click(outgoing.locator('[data-follow="Uranus"]'))
    await current('Uranus')
    assert.equal(new URL(await source.getAttribute('href')).hostname, 'en.wikipedia.org')
    await page.goto(new URL(permalink, home).href)
    await current('Anni Albers')
    assert.deepEqual(await trail.locator('li').allTextContents(), ['Overview', 'Anni Albers'])
    const marker = page.locator('details').filter({ has: page.getByRole('button', { name:'Apply marker', includeHidden:true }) }).last()
    const summary = marker.locator(':scope > summary')
    await click(summary)
    await click(marker.getByRole('button', {name:'Teal ink'}))
    await marker.getByLabel('Shape for this node').selectOption('square')
    await click(marker.getByRole('button', {name:'Apply marker'}))
    await current('Anni Albers')
    await summary.getByText('Custom', {exact:true}).waitFor()
    await click(page.getByRole('button', {name:'Undo document edit'}))
    await summary.getByText('Inherited', {exact:true}).waitFor()
    await click(page.getByRole('button', {name:'Redo document edit'}))
    await summary.getByText('Custom', {exact:true}).waitFor()
    await click(page.getByRole('button', {name:'JSON commands'}))
    const [download] = await Promise.all([page.waitForEvent('download'), click(page.getByRole('button', {name:'Download graph',exact:true}))])
    const saved = JSON.parse(await readFile(await download.path(), 'utf8'))
    assert.deepEqual(saved.nodes.filter(n => n.markerColor || n.markerShape).map(n => [n.id,n.markerColor,n.markerShape]),
      [['Anni_Albers','#39796e','square']])
    assert.equal(saved.nodes.length, 15)
    assert.match(saved.attribution, /Wikipedia contributors/)
    assert.equal(saved.licenseUrl, 'https://creativecommons.org/licenses/by-sa/4.0/')
    assert.ok(saved.nodes.every(n => Number.isSafeInteger(n.wikipediaRevision)))
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    assert.equal(requests.some((u) => u.includes('wikipedia.org')), false)
    const schema = await page.evaluate(async () => (await fetch(new URL('../drawing-style.schema.json', location.href))).json())
    assert.deepEqual(schema.properties.fill.enum, ['solid','hachure','cross-hatch'])
    assert.deepEqual(errors, [])
    return { datasets: 2, articles: 31, crossGroupBack: true, articlePermalink: true, input: touch ? 'touch' : 'keyboard and mouse' }
  } finally { await page.close() }
}
