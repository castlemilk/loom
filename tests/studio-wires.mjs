import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

export async function studioWires(context, url) {
  const page = await context.newPage()
  page.setDefaultTimeout(18000)
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  const shots = new URL('../artifacts/studio/', import.meta.url)
  await mkdir(shots, {recursive:true})
  try {
    await page.goto(url + '?example=wires#settings-style')
    await page.locator('#graph[data-ready]').waitFor()
    const schema = await page.evaluate(async () => (await fetch(new URL('../wire-effects.schema.json', location.href))).json())
    assert.deepEqual(schema.properties.direction.enum, ['none','arrow','flow'])
    await page.locator('#studio-stage[data-member-detail]').waitFor()
    const section = page.locator('details').filter({ has:page.locator('.wire-direction') }).last()
    if (!await section.evaluate((el) => el.open)) await section.locator('summary').first().click()
    const radio = (name) => section.getByRole('radio', { name, exact:true })
    assert.equal(await radio('Flow').isChecked(), true)
    assert.equal(await page.locator('#wire-scope').inputValue(), 'all')
    await section.getByText(/Reduced motion is on/).waitFor()
    await page.screenshot({path:fileURLToPath(new URL('wire-effects.png', shots))})
    await radio('Flow').focus()
    await page.keyboard.press('ArrowLeft')
    assert.equal(await radio('Arrows').isChecked(), true)
    assert.equal(await page.locator('#wire-speed').count(), 0)
    await page.keyboard.press('ArrowLeft')
    assert.equal(await radio('Off').isChecked(), true)
    assert.equal(await page.locator('#wire-scope').count(), 0)
    const spacing = page.locator('#wire-separation')
    await spacing.press('Home')
    await spacing.press('ArrowRight')
    assert.equal(await page.locator('#wire-separation-value').innerText(), '1 px')
    await section.getByText('Flow', {exact:true}).click()
    await page.locator('#wire-scope').selectOption('selected')
    await page.locator('#wire-speed').press('End')
    assert.equal(await page.locator('#wire-speed-value').innerText(), '240 px/s')
    await page.emulateMedia({reducedMotion:'no-preference'})
    await section.getByText(/Reduced motion is on/).waitFor({state:'hidden'})
    await page.emulateMedia({reducedMotion:'reduce'})
    await page.locator('#pause').click()
    const totals = await page.locator('#totals').textContent()
    await page.getByRole('button', {name:'Connect nodes'}).click()
    const from = page.getByLabel('From', {exact:true}), to = page.getByLabel('To', {exact:true})
    await from.fill('materials-4')
    const box = await page.locator('#graph').boundingBox()
    await page.mouse.move(box.x + box.width * .61, box.y + box.height * .46)
    await page.locator('.wire-preview[data-active]').waitFor()
    await to.fill('materials-3')
    const locked = page.locator('.wire-preview[data-active][data-snapped]')
    await locked.waitFor()
    const d = await locked.locator('path').getAttribute('d')
    assert.ok(d.startsWith('M') && d.includes('C'))
    await page.screenshot({path:fileURLToPath(new URL('wire-preview.png', shots))})
    await to.fill('materials-4')
    await page.waitForFunction((old) => document.querySelector('.wire-preview path')?.getAttribute('d') !== old, d)
    await to.press('Escape')
    assert.equal(await page.locator('.wire-preview').count(), 0)
    assert.equal(await page.locator('#totals').textContent(), totals)
    assert.equal(await page.getByRole('button', {name:'Undo document edit'}).isDisabled(), true)
    assert.deepEqual(errors, [])
    return { controls:'keyboard and pointer', snappedPreview:'paused graph', cancelled:true }
  } finally { await page.close() }
}
