import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { chooseGraph } from './graph-picker.mjs'

export async function studioDrilldown(page, url) {
  const showcase = new URL(url)
  showcase.searchParams.set('example', 'drilldown')
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  const control = (id) => page.locator('#' + id)
  const nav = page.getByRole('tablist', { name: 'Graph settings' })
  const tab = (name) => nav.getByRole('tab', { name, exact: true })
  const trail = page.getByRole('navigation', { name: 'Graph drilldown' })
  const group = page.locator('#legend button[data-group="Optics"]')
  const bubble = page.locator('.graph-boundaries [data-taxonomy="section"][data-bubble="Optics"]')
  const shots = new URL('../artifacts/studio/', import.meta.url)
  await mkdir(shots, { recursive: true })
  const capture = async (name, expectedLabels) => {
    await control('perf-toggle').click()
    await page.locator('#perf-panel[data-state="Idle"]').waitFor({ timeout: 20000 })
    if (expectedLabels !== undefined) {
      const counts = await page.getByText('Draws / labels', { exact: true }).locator('..').locator('dd').textContent()
      assert.equal(Number(counts.split(' / ')[1]), expectedLabels, 'Every isolated demo member should have a visible canvas label')
    }
    await control('perf-toggle').click()
    await page.mouse.move(2, 2)
    await page.screenshot({ path: fileURLToPath(new URL(name + '.png', shots)), animations: 'disabled' })
  }
  const totals = (value) => control('totals').getByText(value, { exact: true }).waitFor()
  async function details(name) {
    const summary = page.locator('summary').filter({ hasText: name })
    if (!await summary.evaluate((el) => el.parentElement.open)) await summary.click()
  }
  await page.goto(showcase.href)
  await totals('45 nodes · 88 links')
  await bubble.waitFor({ state: 'attached' })
  const closedOpacity = Number(await bubble.getAttribute('fill-opacity'))
  await capture('atlas-desktop')
  await details('Simulation & diagnostics')
  await control('physics').selectOption('worker')
  await tab('Layout').click()
  await control('blend').focus()
  await control('blend').press('End')
  const overview = await bubble.getAttribute('d')
  await group.click()
  await trail.getByText('8 members').waitFor()
  await totals('45 nodes · 88 links')
  assert.equal(await group.getAttribute('aria-expanded'), 'true')
  assert.equal(await bubble.getAttribute('fill-opacity'), '0')
  assert.equal(await bubble.getAttribute('data-shape'), 'hull')
  await page.waitForFunction(() => {
    document.getElementById('refresh').click()
    return ['transfer','shared'].includes(document.getElementById('transport').textContent) && Number(document.getElementById('ticks').textContent) > 0
  })
  await page.waitForFunction((d) => document.querySelector('[data-taxonomy="section"][data-bubble="Optics"]').getAttribute('d') !== d, overview)
  await tab('Explore').click()
  await capture('atlas-desktop-expanded')
  await details('Drilldown settings')
  await control('member-spacing').press('ArrowRight')
  await control('member-arrangement').selectOption('radial')
  await control('opened-boundary').selectOption('hide')
  await bubble.waitFor({ state: 'detached' })
  await control('opened-boundary').selectOption('fade')
  assert.ok(Math.abs(Number(await bubble.getAttribute('fill-opacity'))-0.2*closedOpacity)<1e-6)
  await control('opened-boundary').selectOption('outline')
  await control('member-arrangement').selectOption('rings')
  await group.click()
  await trail.waitFor({ state: 'detached' })
  assert.equal(await group.getAttribute('aria-expanded'), 'false')
  await control('group-action').selectOption('isolate')
  await control('neighbor-direction').selectOption('outgoing')
  await group.click()
  await totals('8 nodes · 14 links')
  await control('find-node').fill('optics-3')
  await page.locator('[data-result="optics-3"]').click()
  assert.equal(await control('graph').evaluate((el) => el === document.activeElement), true)
  await control('graph').press('Enter')
  await totals('2 nodes · 1 link')
  assert.equal(await trail.locator('li').count(), 3)
  await control('graph').press('Escape')
  await totals('8 nodes · 14 links')
  assert.match(await control('selection').textContent(), /Interference fringes/)
  await trail.getByRole('button', { name: 'Overview', exact: true }).click()
  await totals('45 nodes · 88 links')
  await control('group-action').selectOption('none')
  assert.equal(await group.count(), 0)
  await control('select-action').selectOption('neighbors')
  await control('find-node').fill('optics-3')
  await page.locator('[data-result="optics-3"]').click()
  await totals('3 nodes · 2 links')
  await chooseGraph(page, 'sample')
  await totals('25 nodes · 30 links')
  await trail.waitFor({ state: 'detached' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(showcase.href)
  await totals('45 nodes · 88 links')
  await group.click()
  await trail.getByText('8 members').waitFor()
  await capture('atlas-mobile-expanded')
  const compass = await page.locator('.cloud-compass').boundingBox(), graph = await control('graph').boundingBox()
  assert.ok(compass.y >= graph.y && compass.y + compass.height <= graph.y + graph.height, 'Cloud orientation must be visible inside the stage')
  await page.setViewportSize({ width: 1160, height: 760 })
  const grip = page.getByRole('separator', { name: 'Graph width' })
  await grip.press('Home')
  const narrow = await control('graph').boundingBox(), legend = await control('legend').boundingBox()
  assert.ok(narrow.width <= 221 && legend.height < 48, 'Narrow desktop canvas must keep the legend to one scrollable row')
  await page.setViewportSize({ width: 390, height: 844 })
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)
  assert.ok(overflow <= 1, 'Expanded mobile graph extends outside the viewport')
  await page.setViewportSize({ width: 1160, height: 760 })
  const example = new URL(showcase)
  example.searchParams.set('group', 'Optics')
  example.searchParams.set('bubbles', 'off')
  await page.goto(example.href)
  await totals('8 nodes · 14 links')
  const roster = page.getByRole('list', { name: 'Optics members' })
  const names = ['Optics', 'Prism spectrum', 'Focal plane', 'Interference fringes', 'Beam waist', 'Diffraction limit', 'Grating orders', 'Polarisation']
  assert.deepEqual(await roster.locator('button > span').allTextContents(), names)
  assert.deepEqual(await nav.getByRole('tab').allTextContents(), ['Explore', 'Layout', 'Groups', 'Style'])
  const settingsArt = await nav.locator('img').evaluateAll(async (images) => Promise.all(images.map(async (img) => {
    await img.decode()
    return [new URL(img.src).pathname.split('/').at(-1), img.naturalWidth, img.naturalHeight]
  })))
  assert.deepEqual(settingsArt, ['explore','layout','groups','style'].map((id) => [id + '.webp',224,224]))
  await capture('atlas-optics-members', 8)
  const bubbles = page.getByRole('switch', { name: 'Show group bubbles' })
  await tab('Groups').click()
  await page.getByRole('tabpanel', { name: 'Groups' }).waitFor()
  assert.equal(await bubbles.isChecked(), false)
  assert.equal(await page.locator('.graph-boundaries path').count(), 0)
  await bubbles.check()
  await bubble.waitFor({ state: 'attached' })
  await bubbles.uncheck()
  await tab('Explore').click()
  for (const name of names) {
    const row = roster.getByRole('button', { name, exact: false }).first()
    await row.click()
    await control('selection').getByText(name, { exact: true }).waitFor()
    assert.equal(await row.getAttribute('aria-pressed'), 'true')
  }
  await page.getByRole('button', { name: 'In context', exact: true }).click()
  await totals('45 nodes · 88 links')
  assert.equal(await trail.locator('li').count(), 2)
  await trail.getByRole('button', { name: 'Show only 8 members' }).click()
  await totals('8 nodes · 14 links')
  assert.equal(await trail.locator('li').count(), 2)
  await control('selection').getByText('Polarisation', { exact: true }).waitFor()
  await trail.getByRole('button', { name: 'Back one level' }).click()
  await totals('45 nodes · 88 links')
  await tab('Groups').click()
  assert.equal(await bubbles.isChecked(), false)
  await tab('Explore').click()
  await page.locator('#legend [data-group="Materials"]').click()
  const materials = page.getByRole('list', { name: 'Materials members' })
  assert.equal(await materials.getByRole('button').count(), 8)
  await page.getByRole('button', { name: 'Next members' }).click()
  await materials.locator('[data-member="materials-14"]').click()
  await control('selection').getByText('Annealing', { exact: true }).waitFor()
  await control('find-node').fill('materials-14')
  assert.equal(await materials.getByRole('button').count(), 1)
  await control('find-node').fill('optics-7')
  await page.locator('[data-result="optics-7"]').click()
  await control('selection').getByText('Polarisation', { exact: true }).waitFor()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(example.href)
  await totals('8 nodes · 14 links')
  await capture('atlas-mobile-members', 8)
  const surface = await control('graph').boundingBox(), breadcrumb = await trail.boundingBox(), toolbar = await page.locator('.stage-tools').boundingBox()
  assert.ok(breadcrumb.y + breadcrumb.height <= surface.y && surface.y + surface.height <= toolbar.y, 'Canvas controls overlap the member drawing area')
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
  assert.deepEqual(errors, [])
  return { overview: [45,88], isolated: [8,14], inspectedMembers: names.length, pagedMembers: 15,
    settingsArt, nested: [2,1], expandedBoundary: 'outline', mobileOverflow: overflow }
}
